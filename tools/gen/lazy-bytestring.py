#!/usr/bin/env python3
"""Generate Data.ByteString.Lazy and Data.ByteString.Lazy.Char8.

    tools/gen/lazy-bytestring.py

A lazy ByteString is its own type, as in bytestring, so that a program
may give instances for both (case-insensitive's FoldCase); underneath it
is the strict, packed one (Data.ByteString.Lazy.Internal), and each
function is Data.ByteString's or Data.ByteString.Char8's, its type
changed by unsafeCoerce (a newtype is erased).  Counts and indices are
Int64, as in bytestring's lazy API (Int64 is an Integer, which an Int's
value is).  The types come from bin/yale-haskell's :type, so the
compiler must be built; rerun this when the strict modules change.
"""
import os, re, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
LIB = os.path.join(ROOT, 'lib', 'haskell98')
YALE = os.path.join(ROOT, 'bin', 'yale-haskell')

# bytestring's lazy API counts in Int64
INT64 = {'length', 'take', 'takeEnd', 'drop', 'dropEnd', 'splitAt', 'index',
         'indexMaybe', '!?', 'elemIndex', 'elemIndices', 'elemIndexEnd',
         'findIndex', 'findIndices', 'count', 'replicate'}
# written by hand below
HAND = {'ByteString', 'fromStrict', 'toStrict', 'fromChunks', 'toChunks'}
# the strict API's only (bytestring's lazy one has no C strings)
STRICT_ONLY = {'packCString', 'packCStringLen', 'useAsCString', 'useAsCStringLen'}


def exports(module):
    path = os.path.join(LIB, *module.split('.')) + '.hs'
    text = open(path).read()
    m = re.search(r'module\s+' + re.escape(module) + r'\s*\((.*?)\)\s*where', text, re.S)
    if m is None:
        sys.exit('no export list in ' + path)
    names = []
    for item in re.split(r',', m.group(1)):
        item = item.strip()
        if item:
            names.append(item[1:-1] if item.startswith('(') else item)
    return names


def types(module, names):
    probe = os.path.join(ROOT, 'build', 'lazy-bytestring-probe.hs')
    with open(probe, 'w') as f:
        f.write('import qualified %s as S\nmain :: IO ()\nmain = return ()\n' % module)
    script = ''.join(':type %s\n' % ('(S.%s)' % n if not n[0].isalpha() else 'S.' + n)
                     for n in names)
    out = subprocess.run([YALE, '--haskell98', '--modern-prelude', 'repl', probe],
                         input=script, capture_output=True, text=True).stdout
    found = {}
    for line in out.splitlines():
        line = re.sub(r'^(Main> )+', '', line)
        m = re.match(r'\(?S\.(.+?)\)? :: (.*)$', line)
        if m:
            found[m.group(1)] = m.group(2)
    os.remove(probe)
    missing = [n for n in names if n not in found]
    if missing:
        sys.exit('no type for %s in %s' % (', '.join(missing), module))
    return found


# ByteString in the strict type is the lazy module's own ByteString
def lazy_type(name, ty):
    if name in INT64:
        ty = re.sub(r'\bInt\b', 'Int64', ty)
    return ty


HEADER = '''-- %(module)s (bytestring): generated by tools/gen/lazy-bytestring.py
-- from %(strict)s; edit the generator, not this file.
-- The lazy ByteString is its own type (Data.ByteString.Lazy.Internal),
-- the strict one underneath: each function is %(strict)s's.
module %(module)s (
    ByteString, fromStrict, toStrict, fromChunks, toChunks,
    %(names)s
  ) where

import Prelude ()
import Prelude (Char, Bool, Int, Integer, Maybe, Ordering, String, IO,
                FilePath)
import qualified %(strict)s as S
import Data.ByteString.Lazy.Internal (ByteString(LBS))
import Data.Int (Int64)
import Data.Word (Word8)
import System.IO (Handle)
import Unsafe.Coerce (unsafeCoerce)

fromStrict :: S.ByteString -> ByteString
fromStrict = LBS

toStrict :: ByteString -> S.ByteString
toStrict (LBS b) = b

fromChunks :: [S.ByteString] -> ByteString
fromChunks bs = LBS (S.concat bs)

toChunks :: ByteString -> [S.ByteString]
toChunks (LBS b) = if S.null b then [] else [b]
'''


def generate(strict, module):
    names = [n for n in exports(strict) if n not in HAND and n not in STRICT_ONLY]
    tys = types(strict, names)
    shown = [('(%s)' % n) if not n[0].isalpha() else n for n in names]
    lines = [HEADER % {'module': module, 'strict': strict,
                       'names': ', '.join(shown)}]
    for n, s in zip(names, shown):
        ref = ('(S.%s)' % n) if not n[0].isalpha() else 'S.' + n
        lines.append('%s :: %s\n%s = unsafeCoerce %s\n' % (s, lazy_type(n, tys[n]), s, ref))
    path = os.path.join(LIB, *module.split('.')) + '.hs'
    with open(path, 'w') as f:
        f.write('\n'.join(lines))
    print('wrote', os.path.relpath(path, ROOT), len(names), 'functions')


generate('Data.ByteString', 'Data.ByteString.Lazy')
generate('Data.ByteString.Char8', 'Data.ByteString.Lazy.Char8')
