import sys
root = sys.argv[1]

def type_code(t, base, n, signed):
    lo = -(2**(n-1)) if signed else 0
    hi = 2**(n-1)-1 if signed else 2**n-1
    norm = (f"norm{t} :: {base} -> {base}\n"
            f"norm{t} x = " +
            (f"let m = x `mod` {2**n} in if m > {hi} then m - {2**n} else m\n" if signed
             else f"x `mod` {2**n}\n"))
    normI = (f"norm{t}I :: Integer -> {base}\n"
             f"norm{t}I i = fromInteger (" +
             (f"let m = i `mod` {2**n} in if m > {hi} then m - {2**n} else m)\n" if signed
              else f"i `mod` {2**n})\n"))
    uns = f"(x `mod` {2**n})" if signed else "x"
    # as GHC: the one quotient that does not fit
    ovf = f"if y == -1 && x == {lo} then error \"arithmetic overflow\" else " if signed else ""
    return f"""
-- {t}: {'signed' if signed else 'unsigned'} {n}-bit integers, kept normalised in {'an' if base=='Int' else 'an'} {base}
newtype {t} = {t} {base} deriving (Eq, Ord)

{norm}
{normI}
lift{t}1 :: ({base} -> {base}) -> {t} -> {t}
lift{t}1 f ({t} x) = {t} (norm{t} (f x))

lift{t}2 :: ({base} -> {base} -> {base}) -> {t} -> {t} -> {t}
lift{t}2 f ({t} x) ({t} y) = {t} (norm{t} (f x y))

instance Show {t} where
  showsPrec p ({t} x) = showsPrec p x

instance Read {t} where
  readsPrec p s = [(fromInteger i, r) | (i, r) <- readsPrec p s]

instance Bounded {t} where
  minBound = {t} ({lo})
  maxBound = {t} {hi}

instance Num {t} where
  (+)         = lift{t}2 (+)
  (-)         = lift{t}2 (-)
  (*)         = lift{t}2 (*)
  negate      = lift{t}1 negate
  abs         = {'lift'+t+'1 abs' if signed else 'id'}
  signum      = lift{t}1 signum
  fromInteger i = {t} (norm{t}I i)

instance Real {t} where
  toRational x = toRational (toInteger x)

instance Enum {t} where
  succ x | x == maxBound = error "Enum.succ{{{t}}}: tried to take `succ' of maxBound"
         | otherwise     = x + 1
  pred x | x == minBound = error "Enum.pred{{{t}}}: tried to take `pred' of minBound"
         | otherwise     = x - 1
  toEnum i | toInteger i >= toInteger (minBound :: {t}) && toInteger i <= toInteger (maxBound :: {t})
                       = fromIntegral i
           | otherwise = error "Enum.toEnum{{{t}}}: tag is outside of bounds"
  fromEnum x = fromInteger (toInteger x)
  enumFrom x = enumFromTo x maxBound
  enumFromThen x y = enumFromThenTo x y (if y >= x then maxBound else minBound)
  enumFromTo x y = map fromInteger [toInteger x .. toInteger y]
  enumFromThenTo x y z = map fromInteger [toInteger x, toInteger y .. toInteger z]

instance Integral {t} where
  quot ({t} x) ({t} y) = {ovf}{t} (norm{t} (quot x y))
  rem ({t} x) ({t} y)  = {t} (norm{t} (rem x y))
  div ({t} x) ({t} y)  = {ovf}{t} (norm{t} (div x y))
  mod ({t} x) ({t} y)  = {t} (norm{t} (mod x y))
  quotRem x y = (quot x y, rem x y)
  divMod x y  = (div x y, mod x y)
  toInteger ({t} x) = toInteger x

instance Ix {t} where
  range (a, b)     = [a .. b]
  index (a, b) i
    | a <= i && i <= b = fromInteger (toInteger i - toInteger a)
    | otherwise        = error "Ix.index{{{t}}}: index out of range"
  inRange (a, b) i = a <= i && i <= b

instance Bits {t} where
  (.&.)        = lift{t}2 (.&.)
  (.|.)        = lift{t}2 (.|.)
  xor          = lift{t}2 xor
  complement   = lift{t}1 complement
  shift ({t} x) i = {t} (norm{t} (shift x i))
  rotate ({t} x) i = let {{ j = i `mod` {n}; u = {uns} }}
                     in {t} (norm{t} ((u `shiftL` j) .|. (u `shiftR` ({n} - j))))
  testBit ({t} x) i = i < {n} && testBit x i
  bitSize _    = {n}
  isSigned _   = {'True' if signed else 'False'}
  popCount ({t} x) = popCount {uns}
"""

def module(name, exports, types, doc):
    body = "".join(type_code(*ty) for ty in types)
    return f"""-- {name}: the Haskell 2010 library module (Report 2010), for Yale
-- Haskell's Haskell 98 dialect.  {doc}
-- Generated by tools/gen/gen-intword.py; edit that, not this file.
module {name} ({exports}) where

import Ix
import Data.Bits
{body}"""

ints = [("Int8","Int",8,True),("Int16","Int",16,True),("Int32","Int",32,True),("Int64","Integer",64,True)]
words = [("Word8","Int",8,False),("Word16","Int",16,False),("Word32","Int",32,False),
         ("Word64","Integer",64,False),("Word","Integer",64,False)]
open(f"{root}/Data/Int.hs","w").write(module("Data.Int", "Int, Int8, Int16, Int32, Int64", ints,
  "Each type is a newtype\n-- over Int (Int64 over Integer, since Int is a 63-bit fixnum) holding the\n-- value normalised to its range, so arithmetic wraps."))
open(f"{root}/Data/Word.hs","w").write(module("Data.Word", "Word, Word8, Word16, Word32, Word64", words,
  "Each type is a newtype\n-- over Int (Word64 and Word over Integer) holding the value reduced\n-- modulo 2^n, so arithmetic wraps.  Word is 64 bits, as in GHC."))
