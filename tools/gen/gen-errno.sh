#!/bin/sh
# gen-errno.sh -- write src/ffi/errno-<os>.lisp, the values of the errno
# constants Foreign.C.Error names (Haskell 2010 Report chapter 27) on
# this system, by compiling a C program.  Constants the system lacks are
# left out (Foreign.C.Error gives them Errno (-1), as GHC does).
#
#   tools/gen/gen-errno.sh            # needs cc
set -e
cd "$(dirname "$0")/../.."
os=$(uname -s | tr A-Z a-z)
out=src/ffi/errno-$os.lisp
names="E2BIG EACCES EADDRINUSE EADDRNOTAVAIL EADV EAFNOSUPPORT EAGAIN EALREADY
EBADF EBADMSG EBADRPC EBUSY ECHILD ECOMM ECONNABORTED ECONNREFUSED ECONNRESET
EDEADLK EDESTADDRREQ EDIRTY EDOM EDQUOT EEXIST EFAULT EFBIG EFTYPE EHOSTDOWN
EHOSTUNREACH EIDRM EILSEQ EINPROGRESS EINTR EINVAL EIO EISCONN EISDIR ELOOP
EMFILE EMLINK EMSGSIZE EMULTIHOP ENAMETOOLONG ENETDOWN ENETRESET ENETUNREACH
ENFILE ENOBUFS ENODATA ENODEV ENOENT ENOEXEC ENOLCK ENOLINK ENOMEM ENOMSG ENONET
ENOPROTOOPT ENOSPC ENOSR ENOSTR ENOSYS ENOTBLK ENOTCONN ENOTDIR ENOTEMPTY
ENOTSOCK ENOTTY ENXIO EOPNOTSUPP EPERM EPFNOSUPPORT EPIPE EPROCLIM EPROCUNAVAIL
EPROGMISMATCH EPROGUNAVAIL EPROTO EPROTONOSUPPORT EPROTOTYPE ERANGE EREMCHG
EREMOTE EROFS ERPCMISMATCH ERREMOTE ESHUTDOWN ESOCKTNOSUPPORT ESPIPE ESRCH
ESRMNT ESTALE ETIME ETIMEDOUT ETOOMANYREFS ETXTBSY EUSERS EWOULDBLOCK EXDEV"
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
{
  echo '#include <errno.h>'
  echo '#include <stdio.h>'
  echo 'int main(void) {'
  for n in $names; do
    printf '#ifdef %s\n  printf("  (\\"%s\\" . %%d)\\n", %s);\n#endif\n' "$n" "$n" "$n"
  done
  echo '  return 0; }'
} > "$tmp/errno.c"
cc -o "$tmp/errno" "$tmp/errno.c"
{
  echo ";;; $out -- errno values on $os (generated by tools/gen/gen-errno.sh)."
  echo
  echo '(cl:in-package "MUMBLE-USER")'
  echo
  echo '(cl:defparameter *errno-values*'
  echo "  '("
  "$tmp/errno"
  echo '    ))'
} > "$out"
echo "wrote $out"
