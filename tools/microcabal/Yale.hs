-- MicroCabal.Backend.Yale: build packages with Yale Haskell.
--
-- tools/microcabal/setup.sh copies this file into a copy of MicroCabal's
-- sources (build/microcabal/src/MicroCabal/Backend/Yale.hs) and patches
-- MicroCabal.Main to offer it (--yale, the default there).
--
-- Yale Haskell compiles from source and caches the compiled units, so a
-- package is installed as its sources: a directory in the package
-- database $CABALDIR/yale-VERSION/packages (src/compiler/csys/packages.mumble):
--
--   NAME-VERSION/src/          every hs-source-dirs tree, merged, and the
--                              autogenerated Paths_NAME module
--   NAME-VERSION/include/DIR/  each include-dirs directory
--   NAME-VERSION/yale-package  name, version, extensions, cpp-options,
--                              include-dirs
--
-- Building a library stages that directory under dist-mcabal/yale and
-- compiles a module importing every exposed module against it; installing
-- copies it into the database and compiles once more there, which fills
-- the unit cache for the installed paths.  An executable is built with
-- `yale-haskell build` (a standalone executable), its sources staged as a
-- package of their own so that its extensions and cpp-options apply.
module MicroCabal.Backend.Yale(yaleBackend) where
import Control.Monad
import Data.List
import Data.Maybe
import Data.Version
import System.Directory
import System.Environment
import MicroCabal.Cabal
import MicroCabal.Env
import MicroCabal.StackageList(readVersion)
import MicroCabal.Unix

yaleBackend :: Env -> IO Backend
yaleBackend env = do
  myale <- lookupEnv "YALE"
  let exe = fromMaybe "yale-haskell" myale
  numVersion <- takeWhile (/= '\n') <$> cmdOut env (exe ++ " --numeric-version")
  return Backend {
    compilerName = "yale",
    compilerVersion = readVersion numVersion,
    compiler = "yale-" ++ numVersion,
    compilerExe = exe,
    doesPkgExist = yaleExists,
    patchDepends = \ _ x -> x,
    patchName = \ _ x -> x,
    buildPkgExe = yaleBuildExe,
    buildPkgLib = yaleBuildLib,
    buildPkgForLib = \ _ _ _ -> error "Yale Haskell: foreign-library is not supported",
    installPkgExe = yaleInstallExe,
    installPkgLib = yaleInstallLib
    }

-- The packages Yale Haskell's own library provides (lib/haskell98/),
-- complete or in the part commonly used.
builtinPackages :: [PackageName]
builtinPackages =
  [ "base", "ghc-prim", "array", "containers", "bytestring", "text",
    "deepseq", "directory", "filepath", "process", "time", "mtl",
    "transformers", "parsec", "pretty", "random", "stm", "QuickCheck",
    "hashable", "unordered-containers", "scientific", "haskeline",
    "ansi-terminal", "utf8-string", "old-time", "old-locale", "xhtml",
    "unix", "knob",
    -- depended on for code compiled only by GHC; there is no Template
    -- Haskell, so a module that imports Language.Haskell.TH fails
    "template-haskell",
    -- compatibility packages whose modules base has
    "fail", "semigroups", "void", "nats", "tagged-compat" ]

-- The installed packages' database.
yaleDB :: Env -> FilePath
yaleDB env = instDir env </> compiler (backend env) </> "packages"

-- Where a build is staged.
stageDB :: Env -> FilePath
stageDB env = distDir env </> "yale"

yaleExists :: Env -> PackageName -> IO Bool
yaleExists env pkg
  | pkg `elem` builtinPackages = return True
  | otherwise = do
      let db = yaleDB env
      b <- doesDirectoryExist db
      if not b then return False else do
        ds <- listDirectory db
        return $ any (isPkgDir pkg) ds

-- "NAME-1.2.3" for NAME.
isPkgDir :: PackageName -> FilePath -> Bool
isPkgDir pkg d =
  case stripPrefix (pkg ++ "-") d of
    Just (c:_) -> c >= '0' && c <= '9'
    _          -> False

-- Every command line starts the same way.
yaleArgs :: Env -> [String] -> String
yaleArgs env dbs =
  unwords $ [compilerExe (backend env), "--haskell98", "--modern-prelude"] ++
            map ("--package-db " ++) dbs ++
            compOptions env

-- Stage NAME-VERSION in the directory db: the source trees, include
-- directories and the description.  Returns the package directory.
stagePackage :: Env -> FilePath -> String -> Version -> [Field] -> IO FilePath
stagePackage env db name vers flds = do
  let pdir    = db </> name ++ "-" ++ showVersion vers
      srcDirs = getFieldStrings flds ["."] "hs-source-dirs"
      incDirs = getFieldStrings flds []    "include-dirs"
      defExts = getFieldStrings flds []    "default-extensions"
      exts    = getFieldStrings flds defExts "extensions"
      lang    = maybeToList (getFieldStringM flds "default-language")
      cppOpts = getFieldStrings flds []    "cpp-options"
  -- $YALE_CPP_OPTIONS: more for every package (-D__GLASGOW_HASKELL__=906
  -- for code that only GHC is expected to compile)
  extraCpp <- maybe [] words <$> lookupEnv "YALE_CPP_OPTIONS"
  rmrf env pdir
  mkdir env (pdir </> "src")
  forM_ (srcDirs ++ [pathModuleDir env]) $ \ d -> copyTree env d (pdir </> "src")
  forM_ incDirs $ \ d -> do
    mkdir env (pdir </> "include" </> d)
    copyTree env d (pdir </> "include" </> d)
  writeFile (pdir </> "yale-package") $ unlines
    [ "name: " ++ name
    , "version: " ++ showVersion vers
    , "extensions: " ++ unwords (lang ++ exts)
    , "cpp-options: " ++ unwords (cppOpts ++ extraCpp)
    , "include-dirs: " ++ unwords [ "include" </> d | d <- incDirs ] ]
  return pdir

-- Copy the directory tree d into dir, without the build directory (a
-- source directory is often the package's own, which holds it).
copyTree :: Env -> FilePath -> FilePath -> IO ()
copyTree env d dir = do
  b <- doesDirectoryExist d
  when b $ do
    cwd <- getCurrentDirectory
    let absDir = if "/" `isPrefixOf` dir then dir else cwd </> dir
    cmd env $ "(cd " ++ d ++ " && tar cf - --exclude ./" ++ distDir env ++ " --exclude ./.git .)" ++
              " | (cd " ++ absDir ++ " && tar xf -)"

-- Compile every module of a package: a program importing them all.
compileModules :: Env -> [FilePath] -> FilePath -> String -> [String] -> IO ()
compileModules env dbs dir name mdls = do
  let mainName = "Yale_check_" ++ map (\ c -> if c == '-' then '_' else c) name
      file = dir </> mainName ++ ".hs"
  writeFile file $ unlines $
    [ "module Main(main) where" ] ++
    [ "import qualified " ++ m | m <- mdls ] ++
    [ "main :: IO ()", "main = return ()" ]
  cmd env $ yaleArgs env dbs ++ " compile " ++ file

-- The modules that can be compiled: not those that use Template Haskell,
-- which Yale Haskell does not have (a package often exposes a TH module
-- next to modules that need none).  They are installed all the same.
buildableModules :: Env -> FilePath -> [String] -> IO [String]
buildableModules env pdir mdls = do
  th <- filterM (usesTH pdir) mdls
  unless (null th) $
    message env 0 $ "Not compiled (Template Haskell): " ++ unwords th
  return (mdls \\ th)

usesTH :: FilePath -> String -> IO Bool
usesTH pdir m = do
  let base = pdir </> "src" </> map (\ c -> if c == '.' then '/' else c) m
  fs <- filterM doesFileExist [base ++ ".hs", base ++ ".lhs"]
  case fs of
    f : _ -> do
      txt <- readFile f
      let ls = filter ("{-# LANGUAGE" `isPrefixOf`) (lines txt)
      return $ any (\ l -> "TemplateHaskell" `isInfixOf` l || "QuasiQuotes" `isInfixOf` l) ls
    [] -> return False

libModules :: [Field] -> [String]
libModules flds = getFieldStrings flds [] "exposed-modules" ++
                  getFieldStrings flds [] "other-modules"

yaleBuildLib :: Env -> Section -> Section -> IO ()
yaleBuildLib env (Section _ _ glob) (Section _ name flds) = do
  let vers = getVersion glob "version"
  pdir <- stagePackage env (stageDB env) name vers flds
  mdls <- buildableModules env pdir (libModules flds)
  mkdir env (yaleDB env)
  if null mdls then
    message env 0 $ "Building library " ++ name ++ " with yale skipped, no modules"
   else do
    message env 0 $ "Building library " ++ name ++ " with yale"
    compileModules env [stageDB env, yaleDB env] (stageDB env) name mdls

yaleInstallLib :: Env -> Section -> Section -> IO ()
yaleInstallLib env (Section _ _ glob) (Section _ name flds) = do
  let vers = getVersion glob "version"
      namever = name ++ "-" ++ showVersion vers
      db = yaleDB env
  mdls <- buildableModules env (stageDB env </> namever) (libModules flds)
  mkdir env db
  -- other versions of the package go: one version is installed at a time
  ds <- listDirectory db
  forM_ (filter (isPkgDir name) ds) $ \ d -> rmrf env (db </> d)
  cmd env $ "cp -R " ++ stageDB env </> namever ++ " " ++ db </> namever
  -- fill the unit cache for the installed sources
  unless (null mdls) $
    compileModules env [db] (stageDB env) name mdls

binYale :: FilePath
binYale = "bin" </> "yale"

-- An executable's sources are staged as the package NAME-exe-VERSION.
yaleBuildExe :: Env -> Section -> Section -> IO FilePath
yaleBuildExe env (Section _ _ glob) (Section _ name flds) = do
  let vers    = getVersion glob "version"
      mainIs  = getFieldString flds "main-is"
      srcDirs = getFieldStrings flds ["."] "hs-source-dirs"
      bin     = distDir env </> binYale </> name
  _ <- findMainDir srcDirs mainIs
  pdir <- stagePackage env (stageDB env) (name ++ "-exe") vers flds
  mkdir env (distDir env </> binYale)
  message env 0 $ "Building executable " ++ bin ++ " with yale"
  cmd env $ yaleArgs env [stageDB env, yaleDB env] ++ " build " ++
            pdir </> "src" </> mainIs ++ " -o " ++ bin
  return bin

findMainDir :: [FilePath] -> FilePath -> IO FilePath
findMainDir [] fn = error $ "cannot find " ++ show fn
findMainDir (d:ds) fn = do
  b <- doesFileExist (d </> fn)
  if b then return d else findMainDir ds fn

yaleInstallExe :: Env -> Section -> Section -> IO ()
yaleInstallExe env _ (Section _ name _) = do
  let binDir = instDir env </> "bin"
  mkdir env binDir
  cpr env (distDir env </> binYale </> name) (binDir </> name)
