-- The installed packages' database.
yaleDB :: Env -> FilePath
yaleDB env = instDir env </> compiler (backend env) </> "packages"

-- Where a build is staged.
stageDB :: Env -> FilePath
stageDB env = distDir env </> "yale"

yaleExists :: Env -> PackageName -> IO Bool
yaleExists env pkg
  | pkg `elem` builtinPackages = return True
  | otherwise = do
      let db = yaleDB env
      b <- doesDirectoryExist db
      if not b then return False else do
        ds <- listDirectory db
        return $ any (isPkgDir pkg) ds

-- "NAME-1.2.3" for NAME.
isPkgDir :: PackageName -> FilePath -> Bool
isPkgDir pkg d =
  case stripPrefix (pkg ++ "-") d of
    Just (c:_) -> c >= '0' && c <= '9'
    _          -> False

-- Every command line starts the same way.
yaleArgs :: Env -> [String] -> String
yaleArgs env dbs =
  unwords $ [compilerExe (backend env), "--haskell98", "--modern-prelude"] ++
            map ("--package-db " ++) dbs ++
            compOptions env

-- Stage NAME-VERSION in the directory db: the source trees, include
-- directories and the description.  Returns the package directory.
stagePackage :: Env -> FilePath -> String -> Version -> [Field] -> IO FilePath
stagePackage env db name vers flds = do
  let pdir    = db </> name ++ "-" ++ showVersion vers
      srcDirs = getFieldStrings flds ["."] "hs-source-dirs"
      incDirs = getFieldStrings flds []    "include-dirs"
      defExts = getFieldStrings flds []    "default-extensions"
      exts    = getFieldStrings flds defExts "extensions"
      -- none given: Haskell98, as Cabal assumes (filemanip's data Ix a
      -- => SRange a, a datatype context)
      lang    = [fromMaybe "Haskell98" (getFieldStringM flds "default-language")]
      cppOpts = getFieldStrings flds []    "cpp-options"
  -- $YALE_CPP_OPTIONS: more for every package (-D__GLASGOW_HASKELL__=906
  -- for code that only GHC is expected to compile)
  extraCpp0 <- maybe [] words <$> lookupEnv "YALE_CPP_OPTIONS"
  -- $YALE_MCABAL_PATCHES/NAME.cpp-options: more for this package only
  -- (-D__GLASGOW_HASKELL__=906 for one that refuses other compilers)
  pkgCpp <- do
    mdir <- lookupEnv "YALE_MCABAL_PATCHES"
    case mdir of
      Nothing -> return []
      Just dir -> do
        let f = dir </> name ++ ".cpp-options"
        b <- doesFileExist f
        if b then words <$> readFile f else return []
  let extraCpp = extraCpp0 ++ pkgCpp
  rmrf env pdir
  mkdir env (pdir </> "src")
  forM_ (srcDirs ++ [pathModuleDir env]) $ \ d -> copyTree env d (pdir </> "src")
  -- a module Yale Haskell's library has is not the package's: a
  -- compatibility package's backport (bifunctor-classes-compat's
  -- Data.Bifoldable for a base without it) would hide the library's
  inLib <- libraryModules env (libModules flds)
  unless (null inLib) $
    message env 0 $ "Not staged (Yale Haskell's library has them): " ++ unwords inLib
  forM_ inLib $ \ m -> do
    let base = pdir </> "src" </> modulePath m
    forM_ [base ++ ".hs", base ++ ".lhs"] $ \ f -> do
      b <- doesFileExist f
      when b $ removeFile f
  -- reexported-modules: M as N makes N a module re-exporting M
  let renames (m : "as" : n : rest) = (m, n) : renames rest
      renames (_ : rest) = renames rest
      renames [] = []
      reexps = renames (words (map (\ c -> if c == ',' then ' ' else c)
                                   (unwords (getFieldStrings flds [] "reexported-modules"))))
  forM_ reexps $ \ (m, n) -> do
    let f = pdir </> "src" </> modulePath n ++ ".hs"
    mkdir env (parentDir f)
    writeFile f $ "module " ++ n ++ " (module " ++ m ++ ") where\nimport " ++ m ++ "\n"
  forM_ incDirs $ \ d -> do
    mkdir env (pdir </> "include" </> d)
    copyTree env d (pdir </> "include" </> d)
  applyPatch env name (pdir </> "src")
  -- (hsc2hs's C program: cc-options' -I too, X11's /opt/X11/include,
  -- and HsFFI.h)
  hsInc <- maybe [] (\ d -> ["-I" ++ d]) <$> lookupEnv "YALE_MCABAL_INCLUDE"
  let ccIncs = filter ("-I" `isPrefixOf`) (getFieldStrings flds [] "cc-options")
  preprocessModules env (pdir </> "src")
    (map ("-I" ++) incDirs ++ ccIncs ++ hsInc ++ filter ("-D" `isPrefixOf`) (cppOpts ++ extraCpp))
    (libModules flds ++ getFieldStrings flds [] "other-modules")
  writeFile (pdir </> "yale-package") $ unlines
    [ "name: " ++ name
    , "version: " ++ showVersion vers
    , "extensions: " ++ unwords (lang ++ exts)
    , "cpp-options: " ++ unwords (cppOpts ++ extraCpp)
    , "include-dirs: " ++ unwords [ "include" </> d | d <- incDirs ] ]
  foreignLine <- buildForeignLibrary env pdir name flds
  unless (null foreignLine) $
    appendFile (pdir </> "yale-package") (unlines foreignLine)
  return pdir

-- A module whose source is a happy grammar (.y, .ly) or an alex lexer
-- (.x) is generated, as Cabal does, with the flags Cabal passes (happy
-- -agc, alex -g); the tools are MicroCabal's (instDir/bin, where they are
-- installed with mcabal install happy alex) or on the PATH.  An hsc2hs
-- source (.hsc) using none of hsc2hs's own constructs (#{const ..},
-- #size, #peek, ...) is a Haskell module with CPP directives, which Yale
-- Haskell's preprocessor reads: it is copied (unix-compat's).  One using
-- them is preprocessed by $YALE_HSC2HS (tools/microcabal/yale-hsc2hs,
-- which the mcabal script names), with the package's include-dirs and
-- cpp-options' -D flags (HSCFLAGS).
preprocessModules :: Env -> FilePath -> [String] -> [String] -> IO ()
preprocessModules env src hscFlags mdls =
  forM_ (nub mdls) $ \ m -> do
    let base = src </> modulePath m
    hs <- or <$> mapM doesFileExist [base ++ ".hs", base ++ ".lhs"]
    unless hs $ do
      let tools = [(".y", "happy", "-agc"), (".ly", "happy", "-agc"), (".x", "alex", "-g")]
      found <- filterM (\ (ext, _, _) -> doesFileExist (base ++ ext)) tools
      hsc <- doesFileExist (base ++ ".hsc")
      case found of
        (ext, tool, flags) : _ -> do
          let local = instDir env </> "bin" </> tool
          b <- doesFileExist local
          let exe = if b then local else tool
          message env 0 $ "Preprocessing " ++ m ++ " with " ++ tool
          cmd env $ exe ++ " " ++ flags ++ " " ++ base ++ ext ++ " -o " ++ base ++ ".hs"
        [] | hsc -> do
          text <- readFile (base ++ ".hsc")
          mhsc <- lookupEnv "YALE_HSC2HS"
          if any hscConstruct (lines text)
            then case mhsc of
              Nothing -> message env 0 $ "Not preprocessed (hsc2hs constructs): " ++ m
              Just exe -> do
                message env 0 $ "Preprocessing " ++ m ++ " with yale-hsc2hs"
                cmd env $ unwords ([exe] ++ hscFlags ++ [base ++ ".hsc", "-o", base ++ ".hs"])
            else do
              -- (__YALE_HSC__: its #included headers give macros, not
              -- text, as for hsc2hs's C program; Yale Haskell's cpp)
              message env 0 $ "Preprocessing " ++ m ++ " (.hsc, CPP only)"
              length text `seq` writeFile (base ++ ".hs")
                ("{-# LANGUAGE CPP #-}\n#define __YALE_HSC__ 1\n" ++ text)
        _ -> return ()

-- A line using one of hsc2hs's constructs: #{...}, or #const, #size,
-- #peek and the rest (as words: #define is CPP's).
hscConstruct :: String -> Bool
hscConstruct l = "#{" `isInfixOf` l || any key (tails l)
  where
    key ('#' : r) = any (\ k -> k `isPrefixOf` r && boundary (drop (length k) r)) keys
    key _ = False
    boundary (c : _) = not (isAlphaNum c || c == '_')
    boundary [] = True
    keys = ["const", "const_str", "size", "peek", "poke", "ptr", "offset",
            "type", "enum", "alignment", "let", "def"]

-- $YALE_MCABAL_PATCHES/NAME.patch (tools/microcabal/patches, which the
-- mcabal script names), if there is one: a patch to the package's staged
-- sources (paths relative to src/, the module tree), for code that only
-- GHC was meant to compile.
applyPatch :: Env -> String -> FilePath -> IO ()
applyPatch env name src = do
  mdir <- lookupEnv "YALE_MCABAL_PATCHES"
  case mdir of
    Nothing -> return ()
    Just dir -> do
      let file = dir </> name ++ ".patch"
      b <- doesFileExist file
      when b $ do
        message env 0 $ "Patching " ++ name ++ " with " ++ file
        cmd env $ "patch -s -p1 -d " ++ src ++ " < " ++ file

-- Copy the directory tree d into dir, without the build directory (a
-- source directory is often the package's own, which holds it).
copyTree :: Env -> FilePath -> FilePath -> IO ()
copyTree env d dir = do
  b <- doesDirectoryExist d
  when b $ do
    cwd <- getCurrentDirectory
    let absDir = if "/" `isPrefixOf` dir then dir else cwd </> dir
    cmd env $ "(cd " ++ d ++ " && tar cf - --exclude ./" ++ distDir env ++ " --exclude ./.git .)" ++
              " | (cd " ++ absDir ++ " && tar xf -)"

-- Compile every module of a package: a program importing them all.
compileModules :: Env -> [FilePath] -> FilePath -> String -> [String] -> IO ()
compileModules env dbs dir name mdls = do
  let mainName = "Yale_check_" ++ map (\ c -> if c == '-' then '_' else c) name
      file = dir </> mainName ++ ".hs"
  writeFile file $ unlines $
    [ "module Main(main) where" ] ++
    [ "import qualified " ++ m | m <- mdls ] ++
    [ "main :: IO ()", "main = return ()" ]
  cmd env $ yaleArgs env dbs ++ " compile " ++ file

-- The modules that can be compiled: not those that use Template Haskell,
-- which Yale Haskell does not have (a package often exposes a TH module
-- next to modules that need none).  They are installed all the same.
buildableModules :: Env -> FilePath -> [String] -> IO [String]
buildableModules env pdir mdls = do
  inLib <- libraryModules env mdls
  let mdls' = mdls \\ inLib
  th <- filterM (usesTH pdir) mdls'
  unless (null th) $
    message env 0 $ "Not compiled (Template Haskell): " ++ unwords th
  return (mdls' \\ th)

-- The modules of MDLS that Yale Haskell's library (lib/haskell98, next to
-- the compiler's bin/) provides.
libraryModules :: Env -> [String] -> IO [String]
libraryModules env mdls = do
  let exe = compilerExe (backend env)
      lib = parentDir (parentDir exe) </> "lib" </> "haskell98"
  b <- doesDirectoryExist lib
  if not b then return [] else
    filterM (\ m -> do
               let base = lib </> modulePath m
               or <$> mapM doesFileExist [base ++ ".hu", base ++ ".hs"]) mdls

parentDir :: FilePath -> FilePath
parentDir = reverse . drop 1 . dropWhile (/= '/') . reverse

modulePath :: String -> FilePath
modulePath = map (\ c -> if c == '.' then '/' else c)

usesTH :: FilePath -> String -> IO Bool
usesTH pdir m = do
  let base = pdir </> "src" </> map (\ c -> if c == '.' then '/' else c) m
  fs <- filterM doesFileExist [base ++ ".hs", base ++ ".lhs"]
  case fs of
    f : _ -> do
      txt <- readFile f
      let ls = filter ("{-# LANGUAGE" `isPrefixOf`) (lines txt)
      return $ any (\ l -> "TemplateHaskell" `isInfixOf` l || "QuasiQuotes" `isInfixOf` l) ls
    [] -> return False

libModules :: [Field] -> [String]
libModules flds = getFieldStrings flds [] "exposed-modules" ++
                  getFieldStrings flds [] "other-modules"

yaleBuildLib :: Env -> Section -> Section -> IO ()
yaleBuildLib env (Section _ _ glob) (Section _ name flds0) = do
  let vers = getVersion glob "version"
  info <- runConfigure env glob name
  let flds = foldr (\ (k, vs) fs -> addFieldStrings k vs fs) flds0 info
  pdir <- stagePackage env (stageDB env) name vers flds
  mdls <- buildableModules env pdir (libModules flds)
  mkdir env (yaleDB env)
  if null mdls then
    message env 0 $ "Building library " ++ name ++ " with yale skipped, no modules"
   else do
    message env 0 $ "Building library " ++ name ++ " with yale"
    compileModules env [stageDB env, yaleDB env] (stageDB env) name mdls

-- build-type: Configure: the package's configure script, once, before
-- its sources are staged (X11's and network's make the headers their
-- .hsc files include: HsX11Config.h, HsNetworkConfig.h), with
-- $YALE_CONFIGURE_ARGS, and XQuartz's X11 where it is (/opt/X11, macOS).
-- Returns the fields of the NAME.buildinfo it writes, which Cabal adds
-- to the library's (X11's cc-options and extra-libraries).
runConfigure :: Env -> [Field] -> String -> IO [(FieldName, [String])]
runConfigure env glob name =
  if fmap (map toLower) (getFieldStringM glob "build-type") /= Just "configure"
    then return []
    else do
      done <- doesFileExist "config.status"
      unless done $ do
        args <- maybe "" id <$> lookupEnv "YALE_CONFIGURE_ARGS"
        xquartz <- doesDirectoryExist "/opt/X11/include"
        let xargs = if xquartz then " --x-includes=/opt/X11/include --x-libraries=/opt/X11/lib" else ""
        message env 0 "Running configure"
        cmd env $ "sh ./configure" ++ xargs ++ " " ++ args
      let bi = name ++ ".buildinfo"
      b <- doesFileExist bi
      if not b then return [] else do
        text <- readFile bi
        return [ (map toLower (takeWhile (/= ':') l), words (drop 1 (dropWhile (/= ':') l)))
               | l <- lines text, ':' `elem` l, not ("--" `isPrefixOf` l) ]

-- FIELD with VALUES added to its own (getFieldStrings takes one field).
addFieldStrings :: FieldName -> [String] -> [Field] -> [Field]
addFieldStrings k vs fs =
  [ f | f@(Field n _) <- fs, n /= k ] ++ [Field k (VItems (getFieldStrings fs [] k ++ vs))]

-- A package's C code: its c-sources (and cxx-sources) compiled with its
-- include-dirs and cc-options, and linked with its extra-libraries,
-- extra-lib-dirs, ld-options and frameworks into one shared library,
-- lib/libHSNAME.so in the package, which Yale Haskell loads with it
-- (its yale-package's foreign-libraries).  A package with libraries but
-- no sources gets one too: loading it loads them (X11's Xlib).  Returns
-- the yale-package's line, or none.
buildForeignLibrary :: Env -> FilePath -> String -> [Field] -> IO [String]
buildForeignLibrary env pdir name flds = do
  let csrcs   = getFieldStrings flds [] "c-sources"
      cxxsrcs = getFieldStrings flds [] "cxx-sources"
      libs    = getFieldStrings flds [] "extra-libraries"
      fworks  = getFieldStrings flds [] "frameworks"
      incDirs = getFieldStrings flds [] "include-dirs"
      ccOpts  = getFieldStrings flds [] "cc-options" ++ getFieldStrings flds [] "cxx-options"
      libDirs = getFieldStrings flds [] "extra-lib-dirs"
      ldOpts  = getFieldStrings flds [] "ld-options"
      out     = "lib" </> "libHS" ++ name ++ ".so"
  if null csrcs && null cxxsrcs && null libs && null fworks then return [] else do
    hsInc <- maybe [] (\ d -> ["-I" ++ d]) <$> lookupEnv "YALE_MCABAL_INCLUDE"
    mkdir env (pdir </> "lib")
    srcs <- if null csrcs && null cxxsrcs
      then do
        let stub = pdir </> "lib" </> "stub.c"
        writeFile stub "/* the package's foreign libraries only */\n"
        return [stub]
      else return (csrcs ++ cxxsrcs)
    message env 0 $ "Building the C code of " ++ name
    cmd env $ unwords $
      [if null cxxsrcs then "cc" else "c++", "-shared", "-fPIC", "-w", "-o", pdir </> out] ++
      hsInc ++ map ("-I" ++) incDirs ++ ccOpts ++ srcs ++
      map ("-L" ++) libDirs ++ map ("-l" ++) libs ++ ldOpts ++
      concatMap (\ f -> ["-framework", f]) fworks
    return ["foreign-libraries: " ++ out]

yaleInstallLib :: Env -> Section -> Section -> IO ()
yaleInstallLib env (Section _ _ glob) (Section _ name flds) = do
  let vers = getVersion glob "version"
      namever = name ++ "-" ++ showVersion vers
      db = yaleDB env
  mdls <- buildableModules env (stageDB env </> namever) (libModules flds)
  mkdir env db
  -- other versions of the package go: one version is installed at a time;
  -- of this version only the sources are replaced (its data and include
  -- files are installed before the library)
  ds <- listDirectory db
  forM_ (filter (isPkgDir name) ds) $ \ d ->
    if d == namever then rmrf env (db </> d </> "src") else rmrf env (db </> d)
  mkdir env (db </> namever)
  cmd env $ "cp -R " ++ stageDB env </> namever ++ "/. " ++ db </> namever
  -- fill the unit cache for the installed sources
  unless (null mdls) $
    compileModules env [db] (stageDB env) name mdls

binYale :: FilePath
binYale = "bin" </> "yale"

-- An executable's sources are staged as the package NAME-exe-VERSION.
yaleBuildExe :: Env -> Section -> Section -> IO FilePath
yaleBuildExe env (Section _ _ glob) (Section _ name flds) = do
  let vers    = getVersion glob "version"
      mainIs  = getFieldString flds "main-is"
      srcDirs = getFieldStrings flds ["."] "hs-source-dirs"
      bin     = distDir env </> binYale </> name
  _ <- findMainDir srcDirs mainIs
  pdir <- stagePackage env (stageDB env) (name ++ "-exe") vers flds
  mkdir env (distDir env </> binYale)
  message env 0 $ "Building executable " ++ bin ++ " with yale"
  cmd env $ yaleArgs env [stageDB env, yaleDB env] ++ " build " ++
            pdir </> "src" </> mainIs ++ " -o " ++ bin
  return bin

findMainDir :: [FilePath] -> FilePath -> IO FilePath
findMainDir [] fn = error $ "cannot find " ++ show fn
findMainDir (d:ds) fn = do
  b <- doesFileExist (d </> fn)
  if b then return d else findMainDir ds fn

yaleInstallExe :: Env -> Section -> Section -> IO ()
yaleInstallExe env _ (Section _ name _) = do
  let binDir = instDir env </> "bin"
  mkdir env binDir
  cpr env (distDir env </> binYale </> name) (binDir </> name)
